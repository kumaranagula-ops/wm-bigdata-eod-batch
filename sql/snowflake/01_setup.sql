-- Snowflake serving layer for the WM gold marts. Run once: `make snowflake-setup`
-- (snow CLI, `wm` connection, key-pair auth). Spark appends one AS_OF_DATE at a time
-- after deleting it first, so reruns are idempotent.
USE ROLE SYSADMIN;
USE WAREHOUSE WM_LOAD_WH;
CREATE DATABASE IF NOT EXISTS WM_DB;
CREATE SCHEMA IF NOT EXISTS WM_DB.GOLD;
USE SCHEMA WM_DB.GOLD;

CREATE TABLE IF NOT EXISTS POSITIONS_DAILY (
    ACCOUNT_ID NUMBER(19,0), ACCOUNT_NUMBER VARCHAR, PARTY_ID NUMBER(19,0), FA_ID NUMBER(10,0),
    SECURITY_ID VARCHAR, CUSIP VARCHAR, TICKER VARCHAR, ASSET_CLASS VARCHAR,
    QUANTITY NUMBER(18,4), AVG_COST NUMBER(18,6), COST_BASIS NUMBER(18,2),
    CLOSE_PRICE NUMBER(18,6), PRICE_DATE DATE, MARKET_VALUE NUMBER(18,2),
    UNREALIZED_GL NUMBER(18,2), AS_OF_DATE DATE
) CLUSTER BY (AS_OF_DATE);

CREATE TABLE IF NOT EXISTS ACCOUNT_VALUATION_DAILY (
    ACCOUNT_ID NUMBER(19,0), ACCOUNT_NUMBER VARCHAR, PARTY_ID NUMBER(19,0), ACCOUNT_TYPE VARCHAR,
    TAX_STATUS VARCHAR, FA_ID NUMBER(10,0), FA_NAME VARCHAR, BRANCH_ID NUMBER(10,0),
    BRANCH_NAME VARCHAR, REGION VARCHAR, SECURITIES_MV NUMBER(18,2), CASH_BALANCE NUMBER(18,2),
    TOTAL_VALUE NUMBER(18,2), UNREALIZED_GL NUMBER(18,2), REALIZED_ST_YTD NUMBER(18,2),
    REALIZED_LT_YTD NUMBER(18,2), EST_TAX_YTD NUMBER(18,2), EQUITY_MV NUMBER(18,2),
    ETF_MV NUMBER(18,2), FIXED_INCOME_MV NUMBER(18,2), MUTUAL_FUND_MV NUMBER(18,2),
    AS_OF_DATE DATE
) CLUSTER BY (AS_OF_DATE);

CREATE TABLE IF NOT EXISTS ADVISOR_BOOK_DAILY (
    AGG_LEVEL VARCHAR, REGION VARCHAR, BRANCH_NAME VARCHAR, FA_ID NUMBER(10,0), FA_NAME VARCHAR,
    NUM_ACCOUNTS NUMBER(19,0), NUM_CLIENTS NUMBER(19,0), AUM NUMBER(22,2),
    UNREALIZED_GL NUMBER(22,2), REALIZED_GL_YTD NUMBER(22,2), RANK_IN_REGION NUMBER(10,0),
    AS_OF_DATE DATE
);

CREATE TABLE IF NOT EXISTS CLIENT_PORTFOLIO_SUMMARY (
    PARTY_ID NUMBER(19,0), NUM_ACCOUNTS NUMBER(19,0), PRIMARY_FA_ID NUMBER(10,0),
    TOTAL_VALUE NUMBER(22,2), CASH_BALANCE NUMBER(22,2), UNREALIZED_GL NUMBER(22,2),
    REALIZED_GL_YTD NUMBER(22,2), EST_TAX_YTD NUMBER(22,2), PCT_EQUITY NUMBER(9,4),
    PCT_ETF NUMBER(9,4), PCT_FIXED_INCOME NUMBER(9,4), PCT_MUTUAL_FUND NUMBER(9,4),
    PCT_CASH NUMBER(9,4), CLIENT_SEGMENT VARCHAR, WEALTH_DECILE NUMBER(10,0), AS_OF_DATE DATE
);

CREATE TABLE IF NOT EXISTS REALIZED_GAINS (
    ACCOUNT_ID NUMBER(19,0), SECURITY_ID VARCHAR, SELL_TRADE_ID VARCHAR, LOT_ID VARCHAR,
    ACQUIRED_DATE DATE, SOLD_DATE DATE, QUANTITY NUMBER(18,4), COST_BASIS NUMBER(18,2),
    PROCEEDS NUMBER(18,2), REALIZED_GL NUMBER(18,2), HOLDING_DAYS NUMBER(10,0), TERM VARCHAR,
    TAX_STATUS VARCHAR, IS_TAXABLE BOOLEAN, AS_OF_DATE DATE
);

